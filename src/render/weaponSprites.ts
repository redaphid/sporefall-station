// Held-weapon SPRITES: hand-placed pixel art, drawn the way a 16-bit sprite
// team draws a prop. One drawing per weapon CLASS per drawn VIEW, on the SAME
// pixel grid as the character art that holds it: the base pack draws 48px
// bodies (grid 1: one art pixel per logical unit), the hi-res pack 96px bodies
// in the same 48-unit footprint (grid 2: two art pixels per unit). A weapon is
// never scaled, smoothed or rotated at render time; the renderer picks the
// drawing for the facing and blits it whole, so every pixel below is a pixel
// on screen next to the character's own.
//
// Why literal rows here and not PNGs in the packs: the drawings carry their
// grip and muzzle as pixels (`@`, `*`) the renderer pins to the hand, they are
// one set per pixel GRID rather than per theme flavour, and keeping them as
// data lets the render-layer tests read every pixel. `scripts/assets/
// weapon_sprites.py` exports them as indexed PNGs for the art pipeline (and
// for painters who need the same design, e.g. the drowner's draw clip).
//
// Ink is the locked palette (scripts/assets/palette.py) only:
//   o  #08080c outline (the cast's outline colour)   *  muzzle / head (outline ink)
//   1  #3c444d steel dark   2 #59636d steel mid   3 #7b8791 steel light
//   h  #a2adb4 the one highlight pixel                @  grip pixel (steel dark)
//   g  #3ce0d8 G2 bubble-glass vial                   w/W/B #4a3419/#6b4d26/#8f6c38 wood/wrap
// `.` is transparent. Silhouette first: a 1px outline closes every drawing.

import { WEAPONS } from '../game/data/items'

/** The drawn weapon classes. Every weapon id maps to one (`weaponClass`). */
export type WeaponClass = 'pistol' | 'longgun' | 'blade' | 'wrench' | 'hammer' | 'rod'
export const WEAPON_CLASSES: readonly WeaponClass[] = ['pistol', 'longgun', 'blade', 'wrench', 'hammer', 'rod']

/** Which way a drawing POINTS on screen (east half; the west half is these
 * mirrored). `e` profile, `se` 3/4 down-forward, `s` toward the camera
 * (foreshortened), `ne` 3/4 up-away, `n` away from the camera. */
export type WeaponView = 'e' | 'se' | 's' | 'ne' | 'n'
export const WEAPON_VIEWS: readonly WeaponView[] = ['e', 'se', 's', 'ne', 'n']

/** Pixel grid of a pack: art pixels per logical unit (the manifest artScale). */
export type ArtGrid = 1 | 2
export const artGridFor = (artScale: number): ArtGrid => (artScale >= 2 ? 2 : 1)

const CLASS_OF: Record<string, WeaponClass> = {
  decanter: 'pistol',
  lullDarter: 'pistol',
  sparkCoil: 'pistol',
  frostCondenser: 'pistol',
  scatterFunnel: 'longgun',
  coilRepeater: 'longgun',
  phosphorHose: 'longgun',
  siphonSpike: 'blade',
  pressureLance: 'wrench',
  cageRam: 'hammer',
}

/** Weapon id → drawn class. Named ids first; an unnamed ranged weapon is a
 * pistol, anything else (an unknown id included) the plain rod, so no weapon
 * is ever invisible. */
export const weaponClass = (id: string): WeaponClass =>
  CLASS_OF[id] ?? (WEAPONS[id]?.kind === 'ranged' ? 'pistol' : 'rod')

/** Ink → 0xRRGGBB, every value from the locked palette. */
