export const WEAPON_ART: Readonly<Record<ArtGrid, Sheet>> = { 1: GRID1, 2: GRID2 }

/** A parsed drawing: RGBA pixels plus the two pixels the renderer needs. */
export interface WeaponDrawing {
  w: number
  h: number
  /** The grip pixel (`@`): pinned under the wielder's fist. */
  grip: { x: number; y: number }
  /** The muzzle / head pixel (`*`): where a mod glow sits. Falls back to the
   * grip for views that hide it (a pistol seen from behind). */
  head: { x: number; y: number }
  /** Row-major RGBA, w*h*4 bytes; transparent where the row has `.`. */
  rgba: Uint8Array
}

const parse = (rows: readonly string[]): WeaponDrawing => {
  const h = rows.length
  const w = Math.max(...rows.map((r) => r.length))
  const rgba = new Uint8Array(w * h * 4)
  let grip: { x: number; y: number } | undefined
  let head: { x: number; y: number } | undefined
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x]
      if (ch === '.') continue
      const ink = WEAPON_INK[ch]
      if (ink === undefined) throw new Error(`weapon art: unknown ink "${ch}"`)
      if (ch === '@') grip = { x, y }
      if (ch === '*') head = { x, y }
      const i = (y * w + x) * 4
      rgba[i] = (ink >> 16) & 0xff
      rgba[i + 1] = (ink >> 8) & 0xff
      rgba[i + 2] = ink & 0xff
      rgba[i + 3] = 0xff
    }
  })
  if (!grip) throw new Error('weapon art: a drawing without a grip pixel')
  return { w, h, grip, head: head ?? grip, rgba }
}

const cache = new Map<string, WeaponDrawing>()

/** The drawing for a class seen from a view, on a pack's pixel grid. */
export const weaponDrawing = (grid: ArtGrid, cls: WeaponClass, view: WeaponView): WeaponDrawing => {
  const key = `${grid}:${cls}:${view}`
  let d = cache.get(key)
  if (!d) {
    d = parse(WEAPON_ART[grid][cls][view])
    cache.set(key, d)
  }
  return d
}
